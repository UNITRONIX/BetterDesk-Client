def rust_escape(value):
    return value.replace("\\", "\\\\").replace('"', '\\"')


def process(path, write):
    stem = os.path.splitext(os.path.basename(path))[0]
    with open(path, encoding="utf-8") as handle:
        text = handle.read()
    translations = TRANSLATIONS.get(stem, {})
    missing = [key for key in KEYS if '("' + key + '",' not in text]
    if not missing:
        return []
    lines = "".join(
        '        ("{key}", "{value}"),\n'.format(
            key=rust_escape(key),
            value=rust_escape(translations.get(key, "")),
        )
        for key in missing
    )
    marker = "    ].iter().cloned().collect();"
    index = text.rfind(marker)
    if index < 0:
        raise SystemExit(f"{path}: append marker not found")
    if write:
        with open(path, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text[:index] + lines + text[index:])
    return missing


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "src", "lang")
    files = sorted(glob.glob(os.path.join(root, "*.rs")))
    failures = []
    for path in files:
        missing = process(path, not args.check)
        if missing:
            failures.append((os.path.basename(path), missing))
    for name, missing in failures:
        print(f"{name}: {len(missing)} missing")
    if failures and args.check:
        return 1
    print(f"locales: {len(files)}, updated: {len(failures)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
